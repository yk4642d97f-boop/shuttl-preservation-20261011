"""Prepare promo2 inputs: the real cloud-analysed rally (data only, no footage) → web/data.js, and a 1920×1080 paper grain.

The rally is the 2026-10-08 iPhone → cloud GPU acceptance sample (research/cloud_upgrade/mobile_sample_20261008).
Only the analysis output is used: 3D flight per shot, hit frames, hitter positions, predicted shot types.
Shot types the analysis got wrong against the human labels are flagged so the film never shows them as a label.

usage: ../promo/.venv/bin/python prep.py
"""
import json
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent
SAMPLE = ROOT.parent / "research/cloud_upgrade/mobile_sample_20261008"

GLYPH = {"short_serve": "serve", "long_serve": "serve", "cross_net": "net", "net": "net", "clear": "clear", "drop": "drop",
         "lift": "lift", "push": "push", "smash": "smash", "drive": "drive", "kill": "kill", "block": "block"}


def rally():
    a = json.loads((SAMPLE / "phone-archive.json").read_text())
    acc = json.loads((SAMPLE / "phone-accuracy.json").read_text())
    ok = {x["predicted_frame"]: x["correct"] for x in acc["stroke_type"]["details"]}
    fps = a["meta"]["fps"]
    r = a["rallies"][0]
    known = {}
    for s in a["segments"]:
        for f, p in zip(s["frames"], s["positions"]):
            known[f] = p
    hits = []
    for sh in r["shots"]:
        h = sh["hit"]
        f = h["frame"]
        # The hit frame itself sits between two fitted segments; take the hitter-side end of the incoming flight
        # or, for the serve, the start of the outgoing one.
        if f not in known:
            prev = [k for k in known if k < f]
            known[f] = known[max(prev)] if prev else sh["segment"]["p0"]
        hits.append({"f": f, "t": round(f / fps, 4), "side": h["hitter"], "pos": [round(v, 3) for v in sh["hitter_pos_world"]],
                     "type": sh.get("shot_type"), "glyph": GLYPH.get(sh.get("shot_type"), "unknown"), "ok": bool(ok.get(f, False))})
    f0, f1 = r["start_frame"], r["end_frame"]
    frames = np.arange(f0, f1 + 1)
    kf = np.array(sorted(k for k in known if f0 <= k <= f1))
    kp = np.array([known[k] for k in kf])
    xyz = np.stack([np.interp(frames, kf, kp[:, i]) for i in range(3)], 1)
    xyz[:, 2] = np.maximum(xyz[:, 2], 0)
    return {
        "fps": fps,
        "f0": int(f0), "f1": int(f1),
        "shuttle": [[round(v, 3) for v in p] for p in xyz.tolist()],
        "hits": hits,
        "landing": [round(v, 3) for v in r["landing_xy"]],
        "processing_s": round(a["processing_time_seconds"], 2) if a.get("processing_time_seconds") else None,
    }


def grain(w=1920, h=1080, seed=0x5EEDCAFE):
    # Same recipe as ShuttlDesign.PaperTexture: sparse ink specks, multiplied over the page.
    rng = np.random.default_rng(seed)
    img = np.full((h, w), 255.0)
    n = int(w * h / (128 * 128) * 700 * 1.1)
    xs, ys = rng.uniform(0, w, n), rng.uniform(0, h, n)
    rs = 0.6 + rng.uniform(0, 1.2, n)
    al = 0.05 + rng.uniform(0, 0.11, n)
    for x, y, r, a in zip(xs, ys, rs, al):
        x0, x1, y0, y1 = int(x - r), int(x + r) + 1, int(y - r), int(y + r) + 1
        yy, xx = np.mgrid[max(0, y0):min(h, y1), max(0, x0):min(w, x1)]
        m = ((xx - x) ** 2 + (yy - y) ** 2) <= r * r
        img[yy[m], xx[m]] *= (1 - a * 0.9)
    Image.fromarray(img.clip(0, 255).astype(np.uint8)).convert("RGB").save(ROOT / "assets/grain.png", optimize=True)


if __name__ == "__main__":
    d = rally()
    (ROOT / "web/data.js").write_text("// Generated by prep.py from the 2026-10-08 phone → cloud sample. Analysis output only.\nconst RALLY = "
                                      + json.dumps(d, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print(len(d["shuttle"]), "frames,", len(d["hits"]), "hits,", sum(h["ok"] for h in d["hits"]), "labels shown")
    grain()
    print("grain ok")
